const actionLifecycles: Record<string, ActionDefinition["asyncLifecycle"]> = {
  submit_batch: { startActionId: "contextdev.submit_batch", statusActionId: "contextdev.get_batch" },
};
const actionFollowUps: Record<string, readonly string[]> = { run_monitor_now: ["contextdev.get_monitor_run"] };
export interface ContextdevEndpoint {
  name: string;
  path: string;
  method: "GET" | "POST" | "PATCH" | "DELETE";
  pathKeys: readonly string[];
  queryKeys: readonly string[];
  headerKeys: Readonly<Record<string, string>>;
  action: ActionDefinition;
}
interface EndpointDefinition extends Omit<ContextdevEndpoint, "action"> {
  description: string;
  operationType: ActionDefinition["operationType"];
  inputSchema: JsonSchema;
  outputSchema: JsonSchema;
}
function endpoint(definition: EndpointDefinition): ContextdevEndpoint {
  const { name, path, method, pathKeys, queryKeys, headerKeys } = definition;
  const action = defineProviderAction("contextdev", {
    name,
    description: definition.description,
    operationType: definition.operationType,
    requiredScopes: [],
    inputSchema: definition.inputSchema,
    outputSchema: definition.outputSchema,
    asyncLifecycle: actionLifecycles[name],
    followUpActions: actionFollowUps[name],
  });
  return { name, path, method, pathKeys, queryKeys, headerKeys, action };
}
