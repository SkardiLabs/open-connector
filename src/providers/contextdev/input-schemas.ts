function parseRules(depth: number): JsonSchema {
  const outputs: JsonSchema[] = [
    s.stringEnum("Output kind.", ["text", "html"]),
    s.string("Attribute selector.", { pattern: "^@.*$" }),
  ];
  if (depth < 5) outputs.push(parseRules(depth + 1));
  return s.object(
    "Named CSS extraction rules, including nested rules.",
    {},
    {
      additionalProperties: s.anyOf("CSS selector or extraction rule.", [
        s.string("CSS selector, optionally followed by an attribute.", {
          minLength: 1,
          maxLength: 2048,
        }),
        s.object(
          "Extraction rule.",
          {
            selector: s.string("CSS selector to match within the current page or parent rule.", {
              minLength: 1,
              maxLength: 2048,
            }),
            type: s.stringEnum("Return the first match with `item` or all matches with `list`.", ["item", "list"]),
            output: s.anyOf(
              "Return text, HTML, an attribute such as `@href`, or nested field rules. Defaults to text.",
              outputs,
            ),
          },
          { required: ["selector"] },
        ),
      ]),
      maxProperties: 100,
    },
  );
}
